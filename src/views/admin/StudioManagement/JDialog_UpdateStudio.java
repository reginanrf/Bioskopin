    private void Btn_SimpanStudioEditActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_Btn_SimpanStudioEditActionPerformed
        // TODO add your handling code here:
        
         if (idStudioYangDiedit == -1) {
            javax.swing.JOptionPane.showMessageDialog(this,
                "Terjadi kesalahan: ID studio tidak ditemukan.",
                "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
         return;
        }
         
        String nama  = Field_NamaStudioEdit.getText().trim();
        String tipe  = Field_TipeStudioEdit.getSelectedItem().toString();
        int    baris = (int)  Spinner_BarisStudioEdit.getValue();
        int    kolom = (int) Spinner_ViewsStudioEdit.getValue();

        if (nama.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this,
                "Nama studio wajib diisi!",
                "Peringatan", javax.swing.JOptionPane.WARNING_MESSAGE);
            Field_NamaStudioEdit.requestFocus();
            return;
        }

        if (baris <= 0 || kolom <= 0) {
            javax.swing.JOptionPane.showMessageDialog(this,
                "Jumlah baris dan kolom harus lebih dari 0!",
                "Peringatan", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        String namaLengkap = nama + " (" + tipe + ")";

        boolean sukses = studioController.updateStudio(idStudioYangDiedit, namaLengkap, baris, kolom);

        if (sukses) {
            javax.swing.JOptionPane.showMessageDialog(this,
                "Data studio berhasil diperbarui!",
                "Sukses", javax.swing.JOptionPane.INFORMATION_MESSAGE);
            this.dispose();
        } else {
            javax.swing.JOptionPane.showMessageDialog(this,
                "Gagal memperbarui data. Periksa koneksi database.",
                "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_Btn_SimpanStudioEditActionPerformed

