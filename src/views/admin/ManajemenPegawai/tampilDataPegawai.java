    private void btnEditDataPegawaiActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditDataPegawaiActionPerformed
        // TODO add your handling code here:
        // Logic Tombol Ubah
        int i = tblPegawai.getSelectedRow();
        if(i == -1){
            JOptionPane.showMessageDialog(this, "Pilih baris data yang mau diubah dari tabel dulu!");
            return;
        }

        // 1. Ambil ID saja
        String id = tblPegawai.getValueAt(i, 0).toString();

        // 2. Lempar ID ke Constructor (Otomatis narik data dari DB)
        EditPegawai edit = new EditPegawai(id);
        edit.setVisible(true);

        // 3. Pasang "mata-mata"
        edit.addWindowListener(new java.awt.event.WindowAdapter() {
            @Override
            public void windowClosed(java.awt.event.WindowEvent e) {
                tampilDataKasir();
            }
        });
    }//GEN-LAST:event_btnEditDataPegawaiActionPerformed

    private void btnLihatDataPegawaiActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLihatDataPegawaiActionPerformed
        // TODO add your handling code here:
        // 1. Cek baris mana yang dipilih di tabel
        int row = tblPegawai.getSelectedRow();
        
        // Kalau bernilai -1, artinya user belum ngeklik baris apa pun
        if(row == -1){
            javax.swing.JOptionPane.showMessageDialog(this, 
                "Pilih baris data pegawai di tabel terlebih dahulu!", 
                "Peringatan", 
                javax.swing.JOptionPane.WARNING_MESSAGE);
            return; // Hentikan proses biar gak error
        }

        // 2. Ambil ID dari baris yang dipilih (Kolom ID ada di index 0)
        String idUser = tblPegawai.getValueAt(row, 0).toString();

        // 3. Buka halaman ProfilePegawai dan kirim ID-nya
        ProfilePegawai profil = new ProfilePegawai(idUser);
        profil.setVisible(true);
    }//GEN-LAST:event_btnLihatDataPegawaiActionPerformed

    private void btnHapusDataPegawaiActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnHapusDataPegawaiActionPerformed
        // TODO add your handling code here:
        // Logic Tombol Hapus
        int row = tblPegawai.getSelectedRow();
        if (row == -1) {
            JOptionPane.showMessageDialog(this, "Pilih baris data yang mau dihapus dulu!");
            return;
        }
        String id = tblPegawai.getValueAt(row, 0).toString();
        int confirm = JOptionPane.showConfirmDialog(this, "Yakin hapus ID " + id + "?", "Konfirmasi", JOptionPane.YES_NO_OPTION);

        if (confirm == JOptionPane.YES_OPTION) {
            try {
                Connection conn = DriverManager.getConnection("jdbc:mysql://localhost:3306/db_bioskop", "root", "");
                PreparedStatement stmt = conn.prepareStatement("DELETE FROM users WHERE id_user = ?");
                stmt.setString(1, id);
                stmt.executeUpdate();

                JOptionPane.showMessageDialog(this, "Data berhasil dihapus!");
                tampilDataKasir(); // Refresh tabel
                conn.close();
            } catch (Exception e) {
                JOptionPane.showMessageDialog(this, "Gagal hapus: " + e.getMessage());
            }
        }
    }//GEN-LAST:event_btnHapusDataPegawaiActionPerformed

