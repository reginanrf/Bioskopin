    public void tampilDataKasir() {
        DefaultTableModel model = new DefaultTableModel(new String[]{"ID", "Nama Lengkap", "Email", "Posisi"}, 0);
        try {
            Connection conn = DriverManager.getConnection("jdbc:mysql://localhost:3306/db_bioskop", "root", "");
            // Query sesuai nama kolom di database lu
            Statement stmt = conn.createStatement();
            ResultSet rs = stmt.executeQuery("SELECT id_user, nama, email, role FROM users WHERE role = 'Kasir'");

            while (rs.next()) {
                model.addRow(new Object[]{
                    rs.getString("id_user"), 
                    rs.getString("nama"), 
                    rs.getString("email"), 
                    rs.getString("role")
                });
            }
            tblPegawai.setModel(model); // Pastikan nama tabel lu tblPegawai
            conn.close();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Gagal tampil data: " + e.getMessage());
        }
    }

